import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {Store} from '../src/store.mjs';

test('v1 migration retains exact assignments, sessions, counters, pending events and receipts; reopen is idempotent',t=>{
  const dir=mkdtempSync(join(tmpdir(),'repostew-migration-')),path=join(dir,'runtime.sqlite');
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const old=new DatabaseSync(path);
  old.exec(`CREATE TABLE kv(key TEXT PRIMARY KEY,value TEXT NOT NULL);
    CREATE TABLE tasks(id TEXT PRIMARY KEY,project TEXT NOT NULL,status TEXT NOT NULL,data TEXT NOT NULL);
    CREATE TABLE runs(id TEXT PRIMARY KEY,owner TEXT NOT NULL,status TEXT NOT NULL,data TEXT NOT NULL);
    CREATE TABLE events(seq INTEGER PRIMARY KEY AUTOINCREMENT,kind TEXT NOT NULL,owner TEXT,data TEXT NOT NULL,consumed INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE candidates(key TEXT PRIMARY KEY,data TEXT NOT NULL,disposition TEXT);
    CREATE INDEX candidate_disposition ON candidates(disposition);
    CREATE TABLE requests(id TEXT PRIMARY KEY,value TEXT NOT NULL);
    CREATE TABLE decisions(run TEXT PRIMARY KEY,task TEXT NOT NULL,data TEXT NOT NULL);`);
  const c={status:'interrupted',session:'C:/existing/c1-session.jsonl',failures:3,requiresReconciliation:true};
  const campaign={id:'existing',fingerprint:'unchanged',hasCandidateSnapshot:true};
  for(const [key,value] of Object.entries({schemaVersion:1,mode:'paused',coordinator:c,campaign}))old.prepare('INSERT INTO kv VALUES (?,?)').run(key,JSON.stringify(value));
  const task={id:'w1',projectKey:'fixture.local/old/repo',status:'interrupted',cwd:'C:/existing/task',attempts:4,failures:2,continuations:3,brief:{finishReturn:'retain original'},runId:'old-run'};
  old.prepare('INSERT INTO tasks VALUES (?,?,?,?)').run(task.id,task.projectKey,task.status,JSON.stringify(task));
  const run={id:'old-run',owner:'w1',session:'C:/existing/task/session.jsonl',status:'ended',treeStopped:true,report:{outcome:'blocked',blocker:'retained gate'}};
  old.prepare('INSERT INTO runs VALUES (?,?,?,?)').run(run.id,run.owner,run.status,JSON.stringify(run));
  old.prepare('INSERT INTO events(seq,kind,owner,data,consumed) VALUES (?,?,?,?,?)').run(42,'worker_result','w1',JSON.stringify({runId:run.id}),0);
  old.prepare('INSERT INTO candidates VALUES (?,?,?)').run('fixture.local/new/repo',JSON.stringify({project:{host:'fixture.local',namespace:'new',repo:'repo'}}),null);
  old.prepare('INSERT INTO requests VALUES (?,?)').run('uncertain-message',JSON.stringify({status:'delivery-unknown'}));old.close();
  let store=new Store(path);
  assert.equal(store.get('schemaVersion'),2);assert.equal(store.get('mode'),'paused');
  assert.deepEqual(store.task('w1'),{...task,coordinatorId:'c1'});
  assert.deepEqual(store.run('old-run'),{...run,role:'worker',coordinatorId:'c1'});
  assert.equal(store.coordinator('c1').session,c.session);assert.equal(store.coordinator('c1').failures,3);
  assert.deepEqual(store.get('campaign'),campaign);
  assert.equal(store.events(100,'c1')[0].seq,42);assert.equal(store.events(100,'c2').length,0);
  assert.equal(store.remainingCandidates('c1'),1);assert.equal(store.receipt('uncertain-message').status,'delivery-unknown');
  assert.equal(store.db.prepare("SELECT count(*) AS n FROM kv WHERE key IN ('campaign','coordinator')").get().n,0);
  store.close();store=new Store(path);assert.equal(store.tasks().length,1);assert.equal(store.events().length,1);assert.equal(store.remainingCandidates(),1);store.close();
});
